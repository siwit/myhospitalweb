-- สถิติระยะเวลารอคอยแบบไม่ระบุตัวตน (ไม่มี HN/VN)
CREATE TABLE IF NOT EXISTS waittime_visit_anon (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  source_hash CHAR(64) NOT NULL,
  hospitalcode VARCHAR(10) DEFAULT NULL,
  vstdate DATE NOT NULL,
  vsttime TIME DEFAULT NULL,
  vst_hour TINYINT UNSIGNED DEFAULT NULL,
  is_appointment_visit TINYINT(1) NOT NULL DEFAULT 0,
  is_er_visit TINYINT(1) NOT NULL DEFAULT 0,
  main_depcode VARCHAR(10) DEFAULT NULL,
  main_department VARCHAR(150) DEFAULT NULL,
  screening_depcode VARCHAR(10) DEFAULT NULL,
  screening_department VARCHAR(150) DEFAULT NULL,
  doctor_depcode VARCHAR(10) DEFAULT NULL,
  doctor_department VARCHAR(150) DEFAULT NULL,
  pharmacy_depcode VARCHAR(10) DEFAULT NULL,
  pharmacy_department VARCHAR(150) DEFAULT NULL,
  cur_depcode VARCHAR(10) DEFAULT NULL,
  current_department VARCHAR(150) DEFAULT NULL,
  wait_screen_minutes INT DEFAULT NULL,
  on_screen_minutes INT DEFAULT NULL,
  wait_doctor_minutes INT DEFAULT NULL,
  doctor_minutes INT DEFAULT NULL,
  wait_drug_minutes INT DEFAULT NULL,
  total_opd_minutes INT DEFAULT NULL,
  lab_item_count INT DEFAULT NULL,
  lab_wait_receive_minutes INT DEFAULT NULL,
  lab_process_minutes INT DEFAULT NULL,
  lab_total_minutes INT DEFAULT NULL,
  lab_order_time DATETIME DEFAULT NULL,
  lab_receive_time DATETIME DEFAULT NULL,
  lab_report_time DATETIME DEFAULT NULL,
  xray_item_count INT DEFAULT NULL,
  xray_wait_minutes INT DEFAULT NULL,
  xray_process_minutes INT DEFAULT NULL,
  xray_total_minutes INT DEFAULT NULL,
  synced_at DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_waittime_source_hash (source_hash),
  KEY idx_waittime_vstdate (vstdate),
  KEY idx_waittime_vst_hour (vst_hour),
  KEY idx_waittime_main_dep (main_depcode)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS waittime_sync_log (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  date_from DATE NOT NULL,
  date_to DATE NOT NULL,
  row_count INT NOT NULL DEFAULT 0,
  status VARCHAR(30) NOT NULL DEFAULT 'ok',
  message VARCHAR(500) DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  KEY idx_waittime_sync_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
